"""
DRAPE Pydantic Schemas: Razorpay Payments & Verification.

Validates payment session initiation, HMAC signature verification, and webhook payloads.
Conforms to ADR-001 and SYSTEM_ARCHITECTURE.md.
"""

from typing import Optional
from pydantic import BaseModel, Field


class RazorpayCreateOrderRequest(BaseModel):
    """Payload to initiate Razorpay payment order for an existing pending order."""
    order_id: str = Field(..., description="DRAPE internal order UUID")


class RazorpayCreateOrderResponse(BaseModel):
    """Client configuration for opening Razorpay checkout popup."""
    razorpay_order_id: str
    amount_cents: int
    currency: str
    key_id: str
    order_number: str
    customer_name: Optional[str] = None
    customer_email: Optional[str] = None
    customer_phone: Optional[str] = None


class RazorpayVerifyPaymentRequest(BaseModel):
    """Client-submitted payment verification payload."""
    order_id: str = Field(..., description="DRAPE internal order UUID")
    razorpay_order_id: str = Field(..., description="Razorpay order ID")
    razorpay_payment_id: str = Field(..., description="Razorpay payment ID")
    razorpay_signature: str = Field(..., description="HMAC-SHA256 signature generated by Razorpay")


class PaymentVerificationResponse(BaseModel):
    """Response confirming payment verification status."""
    success: bool
    order_id: str
    order_number: str
    status: str
    payment_status: str
    transaction_id: str
    message: str

